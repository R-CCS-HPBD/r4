/**
 * Research Strategy Engine — Phase 11.
 *
 * The Strategy Engine sits between the Planner and the Reasoning Engine.
 * - Planner answers: "What is the research goal?"
 * - Strategy answers: "What is the highest-value next action?"
 * - Reasoning answers: "What is true?"
 *
 * The Strategy Engine is NOT an LLM call. It is a structured
 * optimization layer that uses the knowledge graph state, active
 * agent budgets, and historical action outcomes to select the next
 * action.
 *
 * Architectural Invariants:
 * - Strategy Engine never calls the Reasoning Engine directly
 * - Strategy Engine reads runtime state (agents, queue, mission control)
 * - Strategy Engine outputs ranked ActionCandidate[] — the Planner/UX picks
 * - Budget allocation is non-negative: never allocate more than remaining
 */

import { createStore } from "solid-js/store";
import { ulid } from "ulid";
import { agentRuntime, agentActions } from "./agent-runtime";
import type {
  ActionCandidate,
  ActionType,
  BudgetAllocation,
  ExperimentProposal,
  StrategyAssessment,
  AgentRole,
  AgentRuntime,
} from "../types";

// ── Strategy Engine State ────────────────────────────────────────────────

export interface ResearchStrategyStore {
  // Ranked action candidates from the latest assessment
  actionCandidates: ActionCandidate[];
  // Latest strategy assessment
  currentAssessment: StrategyAssessment | null;
  // History of assessments
  assessmentHistory: StrategyAssessment[];
  // Budget allocation across agents
  budgetAllocation: BudgetAllocation | null;
  // Experiment proposals generated by the strategy engine
  experimentProposals: ExperimentProposal[];
}

const initialState: ResearchStrategyStore = {
  actionCandidates: [],
  currentAssessment: null,
  assessmentHistory: [],
  budgetAllocation: null,
  experimentProposals: [],
};

const [strategyStore, setStrategyStore] = createStore<ResearchStrategyStore>(initialState);

export { strategyStore };

// ── Strategy Engine Actions ──────────────────────────────────────────────

export const strategyActions = {
  /**
   * Rank candidate actions based on current runtime state.
   *
   * Scoring heuristic (deterministic, no LLM):
   * - Base score from action type (verify > generate > read > review)
   * - Bonus if action targets a low-confidence hypothesis
   * - Penalty if dependencies are unsatisfied
   * - Penalty if estimated cost exceeds remaining budget
   * - Bonus if matching agent is idle
   */
  rankActions(context?: {
    activeAgents?: AgentRuntime[];
    pendingQueueItems?: { id: string; intent: ActionType; dependencies: string[] }[];
    hypotheses?: { id: string; statement: string; confidence: number }[];
    budget?: { remaining: number; burnRate: number; estimatedRunway: number };
  }): ActionCandidate[] {
    const activeAgents = context?.activeAgents ?? agentRuntime.agents.filter(
      (a) => a.state === "running" || a.state === "planning" || a.state === "waiting",
    );
    const hypotheses = context?.hypotheses ?? agentRuntime.missionControl.hypotheses;
    const budget = context?.budget ?? agentRuntime.missionControl.computeBudget;

    const actionTypeBaseScore: Record<ActionType, number> = {
      verify_knowledge: 0.9,
      generate_hypothesis: 0.8,
      extract_knowledge: 0.75,
      read_paper: 0.7,
      review_findings: 0.65,
      analyze_results: 0.6,
      design_experiment: 0.55,
      submit_hpc_job: 0.5,
      prepare_publication: 0.4,
    };

    const candidates: ActionCandidate[] = [];

    for (const hyp of hypotheses) {
      // Generate a "verify knowledge" candidate for each hypothesis
      const confidencePenalty = (1 - hyp.confidence) * 0.3;
      const score = Math.min(
        1,
        actionTypeBaseScore.verify_knowledge + confidencePenalty,
      );
      candidates.push({
        id: ulid(),
        actionType: "verify_knowledge",
        description: `Verify hypothesis ${hyp.id}: ${hyp.statement.slice(0, 40)}`,
        score,
        rationale: `Hypothesis ${hyp.id} has confidence ${(hyp.confidence * 100).toFixed(0)}%; verification reduces uncertainty.`,
        estimatedCost: 0.5,
        estimatedDuration: 1,
        dependencies: [],
        targetHypothesisId: hyp.id,
      });

      // Generate a "design experiment" candidate for low-confidence hypotheses
      if (hyp.confidence < 0.6) {
        candidates.push({
          id: ulid(),
          actionType: "design_experiment",
          description: `Design experiment to test ${hyp.id}`,
          score: Math.min(1, actionTypeBaseScore.design_experiment + (0.6 - hyp.confidence) * 0.5),
          rationale: `Low-confidence hypothesis (${hyp.id}) needs experimental validation.`,
          estimatedCost: 1,
          estimatedDuration: 2,
          dependencies: [`verify-${hyp.id}`],
          targetHypothesisId: hyp.id,
        });
      }
    }

    // Always include a "read paper" candidate if literature agent is idle
    const literatureAgent = activeAgents.find((a) => a.role === "literature");
    if (literatureAgent && literatureAgent.state === "idle") {
      candidates.push({
        id: ulid(),
        actionType: "read_paper",
        description: "Search for missing papers in knowledge graph",
        score: actionTypeBaseScore.read_paper,
        rationale: "Literature agent is idle; reading papers expands knowledge base.",
        estimatedCost: 0.1,
        estimatedDuration: 0.5,
        dependencies: [],
      });
    }

    // Penalize candidates that exceed remaining budget
    for (const c of candidates) {
      if (budget.remaining > 0 && c.estimatedCost > budget.remaining) {
        c.score *= 0.5;
        c.rationale += " (penalized: exceeds remaining budget)";
      }
    }

    // Sort by score descending
    candidates.sort((a, b) => b.score - a.score);

    setStrategyStore("actionCandidates", candidates);
    agentActions.emitEvent("agent_reasoning", {
      source: "strategy_engine",
      action: "rank_actions",
      candidateCount: candidates.length,
    });

    return candidates;
  },

  /**
   * Evaluate the current research strategy and produce an assessment.
   */
  evaluateStrategy(actionHistory?: {
    successful: number;
    failed: number;
    pending: number;
  }): StrategyAssessment {
    const activeAgents = agentRuntime.agents.filter(
      (a) => a.state === "running" || a.state === "planning" || a.state === "waiting",
    );
    const hypotheses = agentRuntime.missionControl.hypotheses;
    const budget = agentRuntime.missionControl.computeBudget;
    const pendingApprovals = agentRuntime.approvalGates.filter((g) => g.status === "pending");
    const blockedAgents = agentRuntime.agents.filter((a) => a.state === "blocked");

    const history = actionHistory ?? {
      successful: agentRuntime.researchQueue.filter((q) => q.status === "completed").length,
      failed: agentRuntime.researchQueue.filter((q) => q.status === "failed").length,
      pending: agentRuntime.researchQueue.filter((q) => q.status === "pending").length,
    };

    const totalActions = history.successful + history.failed;
    const successRate = totalActions > 0 ? history.successful / totalActions : 0;
    const budgetUtilization = budget.remaining > 0 ? 1 - budget.remaining / (budget.remaining + 100) : 1;
    const avgConfidence = hypotheses.length > 0 ? hypotheses.reduce((s, h) => s + h.confidence, 0) / hypotheses.length : 0;

    const overallScore = Math.min(
      1,
      successRate * 0.4 + avgConfidence * 0.3 + (1 - budgetUtilization) * 0.3,
    );

    const strengths: string[] = [];
    const weaknesses: string[] = [];
    const recommendations: string[] = [];
    const coverageGaps: string[] = [];

    if (successRate > 0.7) strengths.push(`High action success rate (${(successRate * 100).toFixed(0)}%)`);
    if (avgConfidence > 0.7) strengths.push(`Strong average hypothesis confidence (${(avgConfidence * 100).toFixed(0)}%)`);
    if (activeAgents.length > 2) strengths.push(`${activeAgents.length} agents actively contributing`);

    if (pendingApprovals.length > 2) weaknesses.push(`${pendingApprovals.length} pending approvals may stall progress`);
    if (blockedAgents.length > 0) weaknesses.push(`${blockedAgents.length} blocked agents`);
    if (budget.remaining < 50) weaknesses.push(`Low remaining compute budget (${budget.remaining} GPU-hrs)`);
    if (successRate < 0.5 && totalActions > 3) weaknesses.push(`Low success rate (${(successRate * 100).toFixed(0)}%)`);

    if (hypotheses.some((h) => h.confidence < 0.5)) coverageGaps.push("Low-confidence hypotheses need verification");
    if (history.pending > 5) coverageGaps.push(`${history.pending} pending actions may indicate bottleneck`);

    if (blockedAgents.length > 0) recommendations.push("Review blocked agents and redirect or cancel");
    if (pendingApprovals.length > 0) recommendations.push("Resolve pending approvals to unblock execution");
    if (budget.remaining < 50) recommendations.push("Request additional compute budget or reduce experiment scope");
    if (hypotheses.length < 3) recommendations.push("Generate additional hypotheses to expand research scope");

    const riskLevel: "low" | "medium" | "high" =
      budget.remaining < 20 || blockedAgents.length > 1 ? "high" :
      pendingApprovals.length > 2 || budget.remaining < 50 ? "medium" : "low";

    const assessment: StrategyAssessment = {
      assessmentId: ulid(),
      timestamp: new Date().toISOString(),
      overallScore,
      strengths,
      weaknesses,
      recommendations,
      coverageGaps,
      budgetUtilization,
      riskLevel,
    };

    setStrategyStore("currentAssessment", assessment);
    setStrategyStore("assessmentHistory", (list) => [assessment, ...list].slice(0, 50));
    agentActions.emitEvent("agent_reasoning", {
      source: "strategy_engine",
      action: "evaluate_strategy",
      overallScore,
      riskLevel,
    });

    return assessment;
  },

  /**
   * Propose experiments for a set of hypotheses.
   */
  proposeExperiments(hypotheses: { id: string; statement: string; confidence: number }[]): ExperimentProposal[] {
    const budget = agentRuntime.missionControl.computeBudget;
    const proposals: ExperimentProposal[] = [];

    for (const hyp of hypotheses) {
      // Skip high-confidence hypotheses — they don't need experiments
      if (hyp.confidence > 0.85) continue;

      const estimatedGpus = hyp.confidence < 0.4 ? 4 : 2;
      const estimatedRuntime = hyp.confidence < 0.4 ? 8 : 4;
      const estimatedCost = estimatedGpus * estimatedRuntime;

      if (estimatedCost > budget.remaining) continue;

      proposals.push({
        id: ulid(),
        hypothesisId: hyp.id,
        title: `Experiment to test ${hyp.id}`,
        description: `Validate hypothesis ${hyp.id}: ${hyp.statement.slice(0, 60)}`,
        methodology: "Computational simulation with controlled parameters",
        expectedOutcome: hyp.confidence < 0.4 ? "Decisive support or refutation" : "Incremental evidence",
        estimatedGpus,
        estimatedRuntime,
        priority: hyp.confidence < 0.4 ? 1 : 2,
        riskLevel: hyp.confidence < 0.3 ? "high" : hyp.confidence < 0.6 ? "medium" : "low",
        dependencies: [],
      });
    }

    // Sort by priority then by confidence ascending (lowest confidence first)
    proposals.sort((a, b) => {
      if (a.priority !== b.priority) return a.priority - b.priority;
      const confA = hypotheses.find((h) => h.id === a.hypothesisId)?.confidence ?? 1;
      const confB = hypotheses.find((h) => h.id === b.hypothesisId)?.confidence ?? 1;
      return confA - confB;
    });

    setStrategyStore("experimentProposals", proposals);
    agentActions.emitEvent("experiment_scheduled", {
      source: "strategy_engine",
      action: "propose_experiments",
      proposalCount: proposals.length,
    });

    return proposals;
  },

  /**
   * Allocate budget across active agents.
   */
  budgetAllocation(activeAgents?: AgentRuntime[]): BudgetAllocation {
    const agents = activeAgents ?? agentRuntime.agents.filter(
      (a) => a.state === "running" || a.state === "planning" || a.state === "waiting",
    );
    const budget = agentRuntime.missionControl.computeBudget;

    const totalBudget = budget.remaining + 100; // assume 100 GPU-hrs already spent
    const allocated = agents.reduce((sum, a) => sum + (a.budget?.maxTokens ? 10 : 5), 0);
    const remaining = Math.max(0, budget.remaining);

    const allocations = agents.map((a) => {
      const agentAlloc = a.budget?.maxTokens ? 10 : 5;
      return {
        agentId: a.id,
        agentRole: a.role,
        allocated: agentAlloc,
        utilized: Math.floor(agentAlloc * 0.3),
        remaining: Math.ceil(agentAlloc * 0.7),
      };
    });

    const allocation: BudgetAllocation = {
      totalBudget,
      allocated,
      remaining,
      allocations,
      burnRate: budget.burnRate,
      estimatedRunway: budget.estimatedRunway,
    };

    setStrategyStore("budgetAllocation", allocation);
    return allocation;
  },

  /**
   * Get the highest-ranked action candidate.
   */
  getTopAction(): ActionCandidate | undefined {
    return strategyStore.actionCandidates[0];
  },

  /**
   * Get all action candidates.
   */
  getActionCandidates(): ActionCandidate[] {
    return strategyStore.actionCandidates;
  },

  /**
   * Reset the strategy store.
   */
  resetStrategy(): void {
    setStrategyStore({
      actionCandidates: [],
      currentAssessment: null,
      assessmentHistory: [],
      budgetAllocation: null,
      experimentProposals: [],
    });
  },
};
