@dataclass
class ChecklistItem:
    """A single deployment checklist item."""

    step: int
    category: str  # prereq | config | validate | smoke
    description: str
    command: str = ""  # optional command to run
    critical: bool = True


@dataclass
class DeploymentChecklist:
    """A full deployment checklist for a profile."""

    profile: str
    envelope: str
    items: list[ChecklistItem] = field(default_factory=list)

    def to_markdown(self) -> str:
        lines = [
            f"# Deployment Checklist: {self.profile}",
            "",
            f"**Envelope**: {self.envelope}",
            "**Generated by**: `tools/deployment_checklist.py`",
            "",
        ]

        categories = {}
        for item in self.items:
            categories.setdefault(item.category, []).append(item)

        category_titles = {
            "prereq": "Prerequisites",
            "config": "Configuration",
            "validate": "Validation",
            "smoke": "Smoke Tests",
        }

        for cat in ("prereq", "config", "validate", "smoke"):
            if cat not in categories:
                continue
            lines.append(f"## {category_titles.get(cat, cat)}")
            lines.append("")
            for item in categories[cat]:
                crit = " **[CRITICAL]**" if item.critical else ""
                lines.append(f"- [ ] {item.step}. {item.description}{crit}")
                if item.command:
                    lines.append("  ```bash")
                    lines.append(f"  {item.command}")
                    lines.append("  ```")
            lines.append("")

        return "\n".join(lines)

    def to_text(self) -> str:
        lines = [f"Deployment Checklist: {self.profile} ({self.envelope})", ""]
        for item in self.items:
            mark = "[CRIT]" if item.critical else "[    ]"
            lines.append(f"  {item.step:2d}. {mark} [{item.category:8s}] {item.description}")
            if item.command:
                lines.append(f"      $ {item.command}")
        return "\n".join(lines)

    def run(self, dry_run: bool = False) -> dict:
        """Execute all checklist items with commands. Returns {step: {'ok': bool, 'error': str|None}}."""
        results: dict = {}
        for item in self.items:
            if not item.command:
                results[item.step] = {"ok": True, "error": None, "skip": "no command"}
                continue

            if dry_run:
                results[item.step] = {
                    "ok": True,
                    "error": None,
                    "skip": "dry-run",
                    "command": item.command,
                }
                continue

            import shlex
            import subprocess

            try:
                # Build command with safe defaults
                cmd = shlex.split(item.command)
                proc = subprocess.run(
                    cmd,
                    capture_output=True,
                    text=True,
                    timeout=120,
                    cwd="/",  # safety: never run from repo root
                )
                results[item.step] = {
                    "ok": proc.returncode == 0,
                    "error": proc.stderr.strip() if proc.returncode != 0 else None,
                    "stdout": proc.stdout.strip()[:500] if proc.returncode == 0 else None,
                }
            except subprocess.TimeoutExpired:
                results[item.step] = {"ok": False, "error": "timed out (120s)", "stdout": None}
            except FileNotFoundError as exc:
                results[item.step] = {
                    "ok": False,
                    "error": f"command not found: {exc}",
                    "stdout": None,
                }
            except Exception as exc:
                results[item.step] = {"ok": False, "error": str(exc), "stdout": None}
        return results

    def run_summary(self, results: dict) -> str:
        """Human-readable summary of execution results."""
        total = len(results)
        passed = sum(1 for r in results.values() if r.get("ok"))
        failed = sum(1 for r in results.values() if not r.get("ok"))
        skipped = sum(1 for r in results.values() if r.get("skip"))
        lines = [
            f"Deployment Checklist Results: {self.profile} ({self.envelope})",
            f"Total: {total} | Passed: {passed} | Failed: {failed} | Skipped: {skipped}",
            "",
        ]
        for step, info in sorted(results.items()):
            status = (
                "✅ PASS" if info.get("ok") else "❌ FAIL" if not info.get("skip") else "⏭ SKIP"
            )
            desc = next((i.description for i in self.items if i.step == step), f"Step {step}")
            lines.append(f"  {status} Step {step}: {desc}")
            if info.get("error"):
                lines.append(f"         Error: {info['error']}")
            if info.get("stdout"):
                lines.append(f"         Output: {info['stdout'][:200]}")
        return "\n".join(lines)


