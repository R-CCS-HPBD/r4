"""Deployment checklist generator (COR-001).

Generates profile-specific deployment checklists and validation scripts
from the runtime support matrix.

Usage:
  python tools/deployment_checklist.py --profile hpc-full
  python tools/deployment_checklist.py --profile k8s-cluster --format markdown
  python tools/deployment_checklist.py --all
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
