_PROFILE_BUILDERS = {
    "hpc-full": _hpc_checklist,
    "hpc-minimal": _hpc_checklist,
    "k8s-cluster": _k8s_checklist,
    "dev-compose": _dev_checklist,
}


def generate_checklist(profile: str) -> DeploymentChecklist | None:
    builder = _PROFILE_BUILDERS.get(profile)
    if builder:
        return builder(profile)
    return None


def main() -> int:
    parser = argparse.ArgumentParser(description="Deployment checklist generator")
    parser.add_argument("--profile", help="Deployment profile")
    parser.add_argument("--format", choices=["text", "markdown"], default="text")
    parser.add_argument("--all", action="store_true", help="Generate all profiles")
    parser.add_argument("--output-dir", help="Write checklists to directory")
    parser.add_argument(
        "--execute",
        action="store_true",
        help="Execute all checklist items with commands (use with caution)",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Show what would be executed without running",
    )
    args = parser.parse_args()

    if args.all:
        profiles = list(_PROFILE_BUILDERS.keys())
    elif args.profile:
        profiles = [args.profile]
    else:
        parser.print_help()
        return 0

    if args.execute or args.dry_run:
        # Execution mode: run commands and report results
        all_results: dict = {}
        for profile in profiles:
            cl = generate_checklist(profile)
            if cl is None:
                print(f"Unknown profile: {profile}", file=sys.stderr)
                print(f"Available: {', '.join(_PROFILE_BUILDERS)}", file=sys.stderr)
                return 1

            results = cl.run(dry_run=args.dry_run)
            all_results[profile] = results
            print(cl.run_summary(results))
            print()

        # Overall status
        total_items = sum(len(r) for r in all_results.values())
        total_passed = sum(sum(1 for v in r.values() if v.get("ok")) for r in all_results.values())
        total_failed = sum(
            sum(1 for v in r.values() if not v.get("ok") and not v.get("skip"))
            for r in all_results.values()
        )
        total_skipped = sum(
            sum(1 for v in r.values() if v.get("skip")) for r in all_results.values()
        )

        print("=" * 60)
        print(
            f"OVERALL: {total_items} items | {total_passed} passed | {total_failed} failed | {total_skipped} skipped"
        )
        if total_failed > 0:
            print("STATUS: ❌ FAIL — deployment readiness NOT confirmed")
            return 1
        else:
            print("STATUS: ✅ PASS — all checks cleared")
            return 0

    # Generation mode (default)
    for profile in profiles:
        cl = generate_checklist(profile)
        if cl is None:
            print(f"Unknown profile: {profile}", file=sys.stderr)
            print(f"Available: {', '.join(_PROFILE_BUILDERS)}", file=sys.stderr)
            return 1

        output = cl.to_markdown() if args.format == "markdown" else cl.to_text()

        if args.output_dir:
            out_dir = Path(args.output_dir)
            out_dir.mkdir(parents=True, exist_ok=True)
            ext = "md" if args.format == "markdown" else "txt"
            out_path = out_dir / f"checklist-{profile}.{ext}"
            out_path.write_text(output + "\n")
            print(f"Wrote {out_path}")
        else:
            print(output)
            print()

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
