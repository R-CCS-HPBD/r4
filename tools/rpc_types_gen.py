#!/usr/bin/env python3
"""TypeScript types for the companion bridge RPC results (plan H-4.4).

Reads the JSON Schema documents in ``contracts/bridge/v1/`` (written by
``tools/rpc_schema_export.py``) and writes
``packages/r4-tui-v3/src/bridge/rpc-types.gen.ts``: one object type per
``$defs`` entry plus ``RpcResultMap`` (verb → result type). The TUI reads
bridge results through ``rpc()`` in ``src/bridge/rpc.ts``, typed by that map.

Stdlib only, no runtime dependency on either side.

Modes:
  --write    regenerate the TS file
  --check    exit 1 when the TS file is stale (default; CI)
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections.abc import Callable
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SCHEMA_DIR = REPO_ROOT / "contracts" / "bridge" / "v1"
DEFAULT_OUT = REPO_ROOT / "packages" / "r4-tui-v3" / "src" / "bridge" / "rpc-types.gen.ts"

_HEADER = """\
// GENERATED by tools/rpc_types_gen.py from contracts/bridge/v1/*.schema.json.
// Do not edit. Regenerate after changing r4/src/r4/companion/ui/rpc_schema.py:
//   python tools/rpc_schema_export.py --write && python tools/rpc_types_gen.py --write
// Optional members (`?`) are keys the bridge may leave out; `| null` keys are
// always sent and may be null. Results allow extra keys (additive protocol).
"""

_IDENTIFIER = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")
_SCALAR_TS = {
    "string": "string",
    "integer": "number",
    "number": "number",
    "boolean": "boolean",
    "null": "null",
}


def _ref_ts(schema: dict[str, Any]) -> str:
    return str(schema["$ref"]).rsplit("/", 1)[-1]


def _result_ts(document: dict[str, Any]) -> str:
    """The verb's result type: the ``$defs`` name for a dataclass root, or the
    inline union for a non-dataclass root (e.g. the two loop-control lanes)."""
    return _ref_ts(document) if "$ref" in document else ts_type(document)


def _any_of_ts(schema: dict[str, Any]) -> str:
    return " | ".join(ts_type(option) for option in schema["anyOf"])


def _enum_ts(schema: dict[str, Any]) -> str:
    return " | ".join(json.dumps(value) for value in schema["enum"])


def _array_ts(schema: dict[str, Any]) -> str:
    item = ts_type(schema["items"]) if "items" in schema else "unknown"
    return f"Array<{item}>" if " " in item else f"{item}[]"


def _object_ts(schema: dict[str, Any]) -> str:
    values = schema.get("additionalProperties")
    return f"Record<string, {ts_type(values) if isinstance(values, dict) else 'unknown'}>"


def _typed_ts(schema: dict[str, Any]) -> str:
    kind = schema["type"]
    if kind == "array":
        return _array_ts(schema)
    if kind == "object":
        return _object_ts(schema)
    return _SCALAR_TS[kind]


_BUILDERS: list[tuple[str, Callable[[dict[str, Any]], str]]] = [
    ("$ref", _ref_ts),
    ("anyOf", _any_of_ts),
    ("enum", _enum_ts),
    ("type", _typed_ts),
]


def ts_type(schema: dict[str, Any]) -> str:
    """The TS type expression for one schema fragment ({} is ``unknown``)."""
    for keyword, builder in _BUILDERS:
        if keyword in schema:
            return builder(schema)
    return "unknown"


def _member(key: str, schema: dict[str, Any], required: set[str]) -> str:
    name = key if _IDENTIFIER.match(key) else json.dumps(key)
    mark = "" if key in required else "?"
    return f"  {name}{mark}: {ts_type(schema)};"


def interface(name: str, schema: dict[str, Any]) -> str:
    """One exported object type for a ``$defs`` entry.

    A type alias, not an ``interface``: object type aliases are assignable to
    ``Record<string, unknown>``, which the TUI's defensive row readers take.
    """
    required = set(schema.get("required", []))
    members = [_member(key, sub, required) for key, sub in schema.get("properties", {}).items()]
    doc = str(schema.get("description") or "").replace("*/", "*\\/")
    lines = [f"/** {doc} */"] if doc else []
    return "\n".join([*lines, f"export type {name} = {{", *members, "};"])


def _load_documents(schema_dir: Path) -> list[dict[str, Any]]:
    return [
        json.loads(path.read_text(encoding="utf-8"))
        for path in sorted(schema_dir.glob("*.schema.json"))
    ]


def _merge_defs(documents: list[dict[str, Any]]) -> dict[str, Any]:
    merged: dict[str, Any] = {}
    for document in documents:
        for name, schema in document.get("$defs", {}).items():
            if merged.setdefault(name, schema) != schema:
                raise ValueError(f"$defs/{name} differs between bridge schemas")
    return merged


def render(schema_dir: Path) -> str:
    """The whole generated TS module for the schemas in ``schema_dir``."""
    documents = _load_documents(schema_dir)
    defs = _merge_defs(documents)
    blocks = [interface(name, defs[name]) for name in sorted(defs)]
    entries = [
        f"  {json.dumps(doc['title'])}: {_result_ts(doc)};"
        for doc in sorted(documents, key=lambda d: str(d["title"]))
    ]
    result_map = "\n".join(
        [
            "/** Covered bridge RPC verb → its result type. */",
            "export interface RpcResultMap {",
            *entries,
            "}",
        ]
    )
    aliases = (
        "export type RpcMethod = keyof RpcResultMap;\n"
        "export type RpcResult<M extends RpcMethod> = RpcResultMap[M];\n"
    )
    return "\n\n".join([_HEADER.rstrip("\n"), *blocks, result_map, aliases])


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--write", action="store_true")
    group.add_argument("--check", action="store_true")
    parser.add_argument("--schemas", type=Path, default=DEFAULT_SCHEMA_DIR)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args(argv)
    content = render(args.schemas)
    if args.write:
        args.out.write_text(content, encoding="utf-8")
        print(f"Wrote {args.out}")
        return 0
    actual = args.out.read_text(encoding="utf-8") if args.out.exists() else None
    if actual != content:
        print(f"DRIFT: {args.out} is stale. Run: python tools/rpc_types_gen.py --write")
        return 1
    print(f"OK: {args.out.name} in sync with contracts/bridge/v1")
    return 0


if __name__ == "__main__":
    sys.exit(main())
