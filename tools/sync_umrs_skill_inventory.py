#!/usr/bin/env python3
"""umrs skill inventory sync — derives the inventory block inside the umrs
skill SKILL.md from `tools/audit_tui_accessibility.py` mechanically.

ADR-105 S4b (2026-11-05): the always-on skill carries only the TUI slash
catalog (the agent suggests slashes to the user). The bridge-verb inventory
— TUI↔runtime RPC the agent cannot call — moved to
``builtin/umrs/references/bridge-verbs.md`` (never injected into a prompt),
which keeps the audit-coverage record without ~500 tokens on every turn.

Usage:
    .venv/bin/python tools/sync_umrs_skill_inventory.py            # write
    .venv/bin/python tools/sync_umrs_skill_inventory.py --check    # drift-detect

Markers:
    <!-- INVENTORY:START --> and <!-- INVENTORY:END -->

The suggestion-table block is hand-curated (context → slash), not generated.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from audit_tui_accessibility import (  # noqa: E402
    bridge_rpc_names,
    slash_top_level,
)

SKILL_PATH = Path("r4/src/r4/companion/builtin/umrs/SKILL.md")
BRIDGE_PATH = Path("r4/src/r4/companion/builtin/umrs/references/bridge-verbs.md")

START = "<!-- INVENTORY:START -->"
END = "<!-- INVENTORY:END -->"


_FAN_PREFIXES = (
    ("workflow.", "workflow.*"),
    ("teamup.", "teamup.*"),
    ("session.", "session.*"),
    ("project_", "project_*"),
    ("assets.", "assets.*"),
    ("circles.", "circles.*"),
    ("loops.", "loops.*"),
    ("traces.", "traces.*"),
    ("provenance.", "provenance.*"),
    ("research_loop.", "research_loop.*"),
)

_STEADY_SKIP = frozenset(
    {
        "initialize",
        "shutdown",
        "get_state",
        "get_status",
        "get_welcome",
        "dispatch_slash_command",
    }
)


def _fanout_counts(bridge: list[str]) -> dict[str, int]:
    return {
        label: sum(1 for v in bridge if v.startswith(prefix)) for prefix, label in _FAN_PREFIXES
    }


def _fanout_line(bridge: list[str]) -> str:
    fanouts = _fanout_counts(bridge)
    return " · ".join(f"{label} ({fanouts[label]})" for _, label in _FAN_PREFIXES if fanouts[label])


def _steady_line(bridge: list[str]) -> str:
    steady = [
        v
        for v in bridge
        if v not in _STEADY_SKIP and not any(v.startswith(prefix) for prefix, _ in _FAN_PREFIXES)
    ]
    return " · ".join(sorted(steady))


def render_inventory() -> str:
    """The skill's block: the slash catalog only."""
    slash_line = " ".join(f"/{n}" for n in slash_top_level())
    return f"""{START}
The **TUI slash catalog** (live slash completion — what users can type):

```
{slash_line}
```
{END}"""


def render_bridge_reference() -> str:
    """The bridge-verb inventory (audit coverage; not loaded into prompts)."""
    bridge = bridge_rpc_names()
    return f"""# Bridge verbs (TUI ↔ runtime RPC) — generated

Generated by `tools/sync_umrs_skill_inventory.py`; do not edit by hand. These
are console RPC verbs, not agent tools: the agent never calls them, so this
inventory is kept out of the always-on `umrs` skill (ADR-105 S4b).

**Bridge verbs** (registered in `BRIDGE_RPC_NAMES` + audit coverage pins;
pairs {len(bridge)} exact): {_fanout_line(bridge)}

Remaining steady rails: {_steady_line(bridge)}.
"""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify drift only")
    args = parser.parse_args(argv)

    path = SKILL_PATH
    body = path.read_text(encoding="utf-8")
    try:
        head, rest = body.split(START, 1)
        mid, tail = rest.split(END, 1)
    except ValueError:
        print(
            "markers not found — insert <!-- INVENTORY:START --> and <!-- INVENTORY:END --> into the skill's platform-knowledge section",
            file=sys.stderr,
        )
        return 2

    wanted = render_inventory()
    have = f"{START}{mid}{END}"
    bridge = render_bridge_reference()
    bridge_have = BRIDGE_PATH.read_text(encoding="utf-8") if BRIDGE_PATH.exists() else ""

    if args.check:
        if have == wanted and bridge_have == bridge:
            print("umrs skill inventory: up to date")
            return 0
        print("umrs skill inventory: DRIFT — rerun without --check to sync")
        return 1

    path.write_text(f"{head}{wanted}{tail}", encoding="utf-8")
    BRIDGE_PATH.write_text(bridge, encoding="utf-8")
    print("umrs skill inventory: synced")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
