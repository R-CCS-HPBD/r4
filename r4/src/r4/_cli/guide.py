"""``r4 guide`` — agent tool playbook discovery (no codebase required)."""

from __future__ import annotations

import hashlib
import json
import sys
from argparse import ArgumentParser, Namespace
from pathlib import Path

from r4_contracts.agent_tool_playbook import (
    AGENT_TOOL_PLAYBOOK,
    AGENT_TOOL_PLAYBOOK_VERSION,
    KNOWLEDGE_OPERATIONS,
    KNOWLEDGE_TOOL_HELP,
    PLATFORM_GUIDE_TOOL_DESCRIPTION,
    RESEARCH_LOOP_OPERATIONS,
    RESEARCH_LOOP_TOOL_HELP,
    RESEARCH_SESSION_OPERATIONS,
    RESEARCH_SESSION_TOOL_HELP,
    platform_guide,
)
from r4_contracts.workflows import WORKFLOW_OPERATIONS, WORKFLOW_TOOL_HELP

from .base import CommandHandler
from .registry import command

_INSTALL_TARGETS = ("cursor", "claude", "copilot", "all")


def _playbook_hash() -> str:
    return hashlib.sha256(AGENT_TOOL_PLAYBOOK.encode("utf-8")).hexdigest()[:12]


def _install_stamp() -> str:
    return (
        f"Generated by r4 guide install — re-run to update\n"
        f"AGENT_TOOL_PLAYBOOK_VERSION={AGENT_TOOL_PLAYBOOK_VERSION}\n"
        f"content_hash={_playbook_hash()}\n"
    )


# (operation prefix, ops tuple, contract help map) — catalog derives from
# contracts so new families show up in `r4 guide tools` without hand-edits.
_PREFIXED_TOOL_HELP = (
    ("workflow", WORKFLOW_OPERATIONS, WORKFLOW_TOOL_HELP),
    ("research_loop", RESEARCH_LOOP_OPERATIONS, RESEARCH_LOOP_TOOL_HELP),
    ("research_session", RESEARCH_SESSION_OPERATIONS, RESEARCH_SESSION_TOOL_HELP),
    ("knowledge", KNOWLEDGE_OPERATIONS, KNOWLEDGE_TOOL_HELP),
)


def _tool_catalog() -> list[dict[str, str]]:
    rows: list[dict[str, str]] = [
        {
            "name": "platform_guide",
            "description": PLATFORM_GUIDE_TOOL_DESCRIPTION,
        }
    ]
    for prefix, operations, help_map in _PREFIXED_TOOL_HELP:
        for op in operations:
            rows.append(
                {
                    "name": f"{prefix}_{op}",
                    "description": help_map[op],
                }
            )
    rows.append(
        {
            "name": "lab_catalog_search",
            "description": (
                "Companion-scoped: search lab catalog metadata (see platform_guide topic=catalog)."
            ),
        }
    )
    rows.append(
        {
            "name": "lab_file_read",
            "description": (
                "Companion-scoped: read a lab file by s3_key (see platform_guide topic=catalog)."
            ),
        }
    )
    return rows


def _write_file(path: Path, body: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body, encoding="utf-8")


def _install_cursor(root: Path) -> Path:
    stamp = _install_stamp()
    path = root / ".cursor" / "rules" / "r4-agent-tools.mdc"
    body = (
        "---\n"
        "description: R4 agent tool playbook (generated)\n"
        "alwaysApply: true\n"
        "---\n\n"
        f"<!-- {stamp.replace(chr(10), ' | ')} -->\n\n"
        f"{AGENT_TOOL_PLAYBOOK}\n"
    )
    _write_file(path, body)
    return path


def _install_claude(root: Path) -> Path:
    stamp = _install_stamp()
    path = root / ".claude" / "r4-guide.md"
    body = f"<!-- {stamp.replace(chr(10), ' | ')} -->\n\n{AGENT_TOOL_PLAYBOOK}\n"
    _write_file(path, body)
    return path


def _install_copilot(root: Path) -> Path:
    stamp = _install_stamp()
    path = root / ".github" / "instructions" / "r4-agent-tools.instructions.md"
    body = (
        "---\n"
        "description: R4 agent tool playbook (generated)\n"
        'applyTo: "**"\n'
        "---\n\n"
        f"<!-- {stamp.replace(chr(10), ' | ')} -->\n\n"
        f"{AGENT_TOOL_PLAYBOOK}\n"
    )
    _write_file(path, body)
    return path


def install_guide(target: str, *, root: Path | None = None) -> list[Path]:
    """Materialize generated editor playbook files under *root* (cwd by default)."""
    base = root or Path.cwd()
    written: list[Path] = []
    targets = _INSTALL_TARGETS[:-1] if target == "all" else (target,)
    for name in targets:
        if name == "cursor":
            written.append(_install_cursor(base))
        elif name == "claude":
            written.append(_install_claude(base))
        elif name == "copilot":
            written.append(_install_copilot(base))
        else:
            raise ValueError(f"Unknown install target: {target}")
    return written


@command
class GuideCommand(CommandHandler):
    """``r4 guide`` — print / list / install the agent tool playbook."""

    name = "guide"
    help = "Agent tool playbook (no codebase required)"

    def register(self, subparsers) -> ArgumentParser:
        p = subparsers.add_parser(
            self.name,
            help=self.help,
            description=(
                "Print the official R4 agent tool playbook, list spine tool "
                "descriptions, or install generated editor rules from contracts."
            ),
        )
        sub = p.add_subparsers(dest="guide_command", title="subcommands")

        tools_p = sub.add_parser(
            "tools",
            help="List companion-relevant tools with contract descriptions",
        )
        tools_p.add_argument(
            "--json",
            dest="as_json",
            action="store_true",
            help="Emit JSON",
        )

        install_p = sub.add_parser(
            "install",
            help="Write generated editor playbook files into the project cwd",
        )
        install_p.add_argument(
            "--target",
            choices=_INSTALL_TARGETS,
            default="cursor",
            help="Editor target (default: cursor)",
        )
        return p

    def handle(self, args: Namespace) -> int:
        action = getattr(args, "guide_command", None)
        if action == "tools":
            return self._tools(args)
        if action == "install":
            return self._install(args)
        print(platform_guide("all"))
        return 0

    def _tools(self, args: Namespace) -> int:
        rows = _tool_catalog()
        if getattr(args, "as_json", False):
            print(json.dumps(rows, indent=2))
            return 0
        for row in rows:
            print(f"{row['name']}: {row['description']}")
        return 0

    def _install(self, args: Namespace) -> int:
        target = getattr(args, "target", "cursor")
        try:
            written = install_guide(target)
        except ValueError as exc:
            print(f"Error: {exc}", file=sys.stderr)
            return 1
        for path in written:
            print(f"Wrote {path}")
        return 0
