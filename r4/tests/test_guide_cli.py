"""Tests for ``r4 guide`` playbook CLI."""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

from r4_contracts.agent_tool_playbook import (
    AGENT_TOOL_PLAYBOOK,
    AGENT_TOOL_PLAYBOOK_VERSION,
    platform_guide,
)

from r4._cli.guide import install_guide


def test_r4_guide_prints_playbook():
    result = subprocess.run(
        [sys.executable, "-m", "r4.cli", "guide"],
        capture_output=True,
        text=True,
        timeout=30,
    )
    assert result.returncode == 0, result.stderr
    assert result.stdout.strip() == platform_guide("all").strip()
    assert result.stdout.strip() == AGENT_TOOL_PLAYBOOK.strip()


def _guide_tool_rows() -> list[dict]:
    result = subprocess.run(
        [sys.executable, "-m", "r4.cli", "guide", "tools", "--json"],
        capture_output=True,
        text=True,
        timeout=30,
    )
    assert result.returncode == 0, result.stderr
    return json.loads(result.stdout)


def test_r4_guide_tools_json_lists_the_canonical_spine():
    names = {row["name"] for row in _guide_tool_rows()}
    expected = {
        "platform_guide",
        "workflow_list",
        "research_loop_start",
        "research_loop_approvals",
        "research_session_create",
        "knowledge_ingest",
    }
    assert expected <= names


def test_r4_guide_tools_json_has_no_rc1_and_names_workflow_name():
    rows = _guide_tool_rows()
    assert not [r["name"] for r in rows if r["name"].startswith("project_research_")]
    start = next(r for r in rows if r["name"] == "research_loop_start")
    assert "workflow_name" in start["description"]


def test_r4_guide_install_cursor(tmp_path: Path):
    written = install_guide("cursor", root=tmp_path)
    assert len(written) == 1
    text = written[0].read_text(encoding="utf-8")
    assert "Generated by r4 guide install" in text
    assert f"AGENT_TOOL_PLAYBOOK_VERSION={AGENT_TOOL_PLAYBOOK_VERSION}" in text
    assert "content_hash=" in text
    assert AGENT_TOOL_PLAYBOOK in text


def test_r4_guide_help_exits_zero():
    result = subprocess.run(
        [sys.executable, "-m", "r4.cli", "guide", "--help"],
        capture_output=True,
        text=True,
        timeout=30,
    )
    assert result.returncode == 0
    assert "usage:" in result.stdout.lower()
