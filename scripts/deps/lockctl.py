#!/usr/bin/env python3
"""Dependency locks for the images the umrs-front converge builds (ADR-100).

The workspace ``uv.lock`` is the one source of versions. Images install from
requirement files exported from it (or, for the two images whose packages are
not workspace members, compiled with ``uv pip compile``), always with
``pip install --no-deps``, so nothing unpinned reaches an image.

Subcommands
  cooldown [--days 7] [--today YYYY-MM-DD]
      Write the release cooldown into the root pyproject.toml: ``exclude-newer``
      = today minus N days, plus one ``exclude-newer-package`` exemption per
      package whose LOCKED version is newer than that (pinned at its own upload
      time), so a refresh never downgrades a deliberate recent bump.
  allow-new PACKAGE...
      Security fast path: exempt PACKAGE from the cooldown up to now. Then run
      ``uv lock --upgrade-package PACKAGE`` and ``lockctl.py export``.
  export [--upgrade] [--upgrade-package PACKAGE]...
      Regenerate every image lock. Workspace locks are exports of uv.lock.
      Compiled locks are constrained to uv.lock's versions (so they agree with
      it on every package both hold, and its scan and fast path cover them),
      with the same cutoff and exemptions as uv.lock; --upgrade re-resolves
      them, --upgrade-package (the fast path) moves PACKAGE, exempt up to now.
  derive-umrs
      Regenerate umrs/src/uv.lock from the workspace lock's versions, so the
      two locks cannot drift (the umrs project alone cannot be locked: its
      r4-contracts dependency is on no index).
  check
      Offline (needs uv, no network): every workspace image lock is exactly
      what `uv export` emits now (no package missing, none extra), every
      compiled lock pins every line and agrees with uv.lock, and
      umrs/src/uv.lock holds the workspace versions.
  changes OLD_UV_LOCK
      `name: old -> new` for every package that moved (for the PR body).

Python 3.10 compatible (the checkout venv); stdlib only.
"""

from __future__ import annotations

