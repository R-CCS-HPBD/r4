PIN_LINE = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)(\[[^\]]*\])?==([^\s;]+)")
URL_LINE = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*) @ https://\S+#sha256=[0-9a-f]{64}$")


def canonical(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _run(cmd: list[str], cwd: Path = ROOT) -> str:
    done = subprocess.run(cmd, cwd=cwd, check=True, capture_output=True, text=True)
    return done.stdout


# ── uv.lock parsing (no tomllib on 3.10) ────────────────────────────────────


@dataclass
class LockedPackage:
    name: str
    versions: set[str] = field(default_factory=set)
    upload_times: list[str] = field(default_factory=list)


def _package_blocks(text: str) -> list[str]:
    return text.split("\n[[package]]\n")[1:]


def parse_uv_lock(text: str) -> dict[str, LockedPackage]:
    """name -> versions and file upload times, from a uv.lock text."""
    packages: dict[str, LockedPackage] = {}
    for block in _package_blocks(text):
        name = re.search(r'^name = "([^"]+)"', block, re.M)
        version = re.search(r'^version = "([^"]+)"', block, re.M)
        if not (name and version):
            continue
        entry = packages.setdefault(canonical(name.group(1)), LockedPackage(name.group(1)))
        entry.versions.add(version.group(1))
        entry.upload_times += re.findall(r'upload-time = "([^"]+)"', block)
    return packages


# ── requirement files ───────────────────────────────────────────────────────


def requirement_lines(text: str) -> list[str]:
    """The requirement lines of a requirements file (no comments, no options)."""
    lines = (line.strip() for line in text.splitlines())
    return [line for line in lines if line and not line.startswith(("#", "-"))]


def pins(text: str) -> dict[str, str]:
    """canonical name -> pinned version for every `name==version` line."""
    found = {}
    for line in requirement_lines(text):
        match = PIN_LINE.match(line)
        if match:
            found[canonical(match.group(1))] = match.group(3)
    return found


def unpinned_lines(text: str) -> list[str]:
    """Requirement lines that are neither `==` pins nor hash-pinned URLs."""
    return [
        line
        for line in requirement_lines(text)
        if not (PIN_LINE.match(line) or URL_LINE.match(line))
    ]


def _blocks(text: str) -> list[list[str]]:
    """Split an exported file into blocks: a requirement and its `# via` lines."""
    blocks: list[list[str]] = []
    for line in text.splitlines():
        if line.startswith((" ", "\t")) and blocks:
            blocks[-1].append(line)
        else:
            blocks.append([line])
    return blocks


def cuda_only(full: str, pruned: str) -> set[str]:
    """torch, torchvision and the CUDA packages nothing but they need."""
    exclusive = set(pins(full)) - set(pins(pruned))
    return {name for name in exclusive if name in TORCH_PINS or CUDA_NAMES.match(name)}


def _block_name(block: list[str]) -> str:
    match = PIN_LINE.match(block[0])
    return canonical(match.group(1)) if match else ""


def cpu_variant(text: str, drop: set[str]) -> str:
    """The lock without the `drop` packages (and their `# via` lines)."""
    kept = [block for block in _blocks(text) if _block_name(block) not in drop]
    return "\n".join(line for block in kept for line in block) + "\n"


def torch_pins(text: str) -> str:
    locked = pins(text)
    return "".join(f"{name}=={locked[name]}\n" for name in TORCH_PINS)


# ── export ──────────────────────────────────────────────────────────────────


def _export(*args: str, cwd: Path = ROOT) -> str:
    return _run(
        [
            "uv",
            "export",
            "--frozen",
            "--no-hashes",
            "--no-header",
            "--no-dev",
            "--no-emit-workspace",
            "--format",
            "requirements-txt",
            *args,
        ],
        cwd=cwd,
    )


def export_workspace(lock: WorkspaceLock, root: Path = ROOT) -> dict[str, str]:
    """Rendered files (relative path -> text) for one workspace image lock."""
    body = _export(*lock.export_args, cwd=root)
    source = "uv.lock (uv export " + " ".join(lock.export_args) + ")"
    head = HEADER.format(cmd="export", source=source)
    tail = "".join(f"{line}\n" for line in lock.extra_lines)
    files = {lock.out: head + body + tail}
    if lock.cpu_out:
        cpu_head = head + "# CPU variant: torch/torchvision come from torch-cpu.lock.txt.\n"
        prune = (f"--prune={name}" for name in TORCH_PINS)
        pruned = _export(*lock.export_args, *prune, cwd=root)
        files[lock.cpu_out] = cpu_head + cpu_variant(body, cuda_only(body, pruned)) + tail
        files[lock.torch_cpu_out] = head + torch_pins(body)
    return files


def cutoff_from_pyproject(text: str, days: int = 7) -> str:
    """The workspace cutoff; before the first `cooldown` run, today minus N days."""
    match = re.search(r'^exclude-newer = "([^"]+)"', text, re.M)
    return match.group(1) if match else cutoff_for(dt.date.today(), days)


# Every uv.lock version as a constraint file for `uv pip compile`. A fixed
# relative name: uv writes it into the `# via` annotations.
CONSTRAINTS = ".lockctl-uv-lock-constraints.txt"


def uv_lock_constraints() -> str:
    return _export("--all-packages", "--all-extras", "--all-groups", "--no-annotate")


def merge_exemptions(*sources: dict[str, str]) -> dict[str, str]:
    """name -> the latest stamp any source gives it."""
    merged: dict[str, str] = {}
    for source in sources:
        for name, stamp in source.items():
            merged[name] = max(merged.get(name, ""), stamp)
    return merged


def compile_exemptions(cutoff: str, packages: list[str], now: str) -> dict[str, str]:
    """The cutoff exemptions a compiled lock needs: every uv.lock package
    locked past the cutoff (a recent bump such as certifi 2026.10.19 is never
    undone), the pyproject's allow-new entries, and the fast-path packages."""
    locked = exemptions(parse_uv_lock(UV_LOCK.read_text()), cutoff)
    current = current_exemptions(PYPROJECT.read_text())
    return merge_exemptions(locked, current, {canonical(name): now for name in packages})


@dataclass(frozen=True)
class CompileOptions:
    cutoff: str
    exempt: dict[str, str]
    upgrade: bool = False
    packages: tuple[str, ...] = ()


def compile_command(lock: CompiledLock, opts: CompileOptions) -> list[str]:
    cmd = ["uv", "pip", "compile", lock.src, "--universal", "--no-header"]
    cmd += ["--python-version", lock.python, "-c", CONSTRAINTS, "-o", lock.out]
    cmd += ["--exclude-newer", opts.cutoff]
    cmd += [f"--exclude-newer-package={n}={s}" for n, s in sorted(opts.exempt.items())]
    cmd += ["--upgrade"] if opts.upgrade else []
    return cmd + [f"--upgrade-package={name}" for name in opts.packages]


def compile_lock(lock: CompiledLock, opts: CompileOptions) -> dict[str, str]:
    _run(compile_command(lock, opts))
    out = ROOT / lock.out
    source = f"{lock.src} (uv pip compile --universal --python-version {lock.python}, -c uv.lock)"
    return {lock.out: HEADER.format(cmd="export", source=source) + out.read_text()}


def write_files(files: dict[str, str]) -> None:
    for rel, text in files.items():
        path = ROOT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"wrote {rel}")


def cmd_export(args: argparse.Namespace) -> int:
    for lock in WORKSPACE_LOCKS.values():
        write_files(export_workspace(lock))
    cutoff = cutoff_from_pyproject(PYPROJECT.read_text())
    packages = tuple(args.upgrade_package)
    exempt = compile_exemptions(cutoff, list(packages), _now())
    opts = CompileOptions(cutoff, exempt, args.upgrade, packages)
    constraints = ROOT / CONSTRAINTS
    constraints.write_text(uv_lock_constraints())
    try:
        for lock in present_compiled_locks():
            write_files(compile_lock(lock, opts))
    finally:
        constraints.unlink()
    return 0


# ── cooldown ────────────────────────────────────────────────────────────────


def _now() -> str:
    return dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def cutoff_for(today: dt.date, days: int) -> str:
    return (today - dt.timedelta(days=days)).strftime("%Y-%m-%dT00:00:00Z")


def exemptions(packages: dict[str, LockedPackage], cutoff: str) -> dict[str, str]:
    """Packages whose locked files are newer than the cutoff -> newest upload time."""
    found = {}
    for name, entry in sorted(packages.items()):
        newest = max(entry.upload_times, default="")
        if newest > cutoff:
            found[name] = _utc_seconds(newest)
    return found


def _utc_seconds(stamp: str) -> str:
    """uv writes upload times with milliseconds; keep whole seconds, rounded up."""
    base = stamp.rstrip("Z").split(".")[0]
    moment = dt.datetime.fromisoformat(base) + dt.timedelta(seconds=1)
    return moment.strftime("%Y-%m-%dT%H:%M:%SZ")


def replace_block(text: str, name: str, body: str) -> str:
    begin, end = f"# >>> lockctl:{name}\n", f"# <<< lockctl:{name}\n"
    start, stop = text.find(begin), text.find(end)
    if start < 0 or stop < start:
        raise SystemExit(f"pyproject.toml lacks the lockctl:{name} markers")
    return text[: start + len(begin)] + body + text[stop:]


def render_cooldown(cutoff: str, days: int, today: dt.date) -> str:
    return (
        f"# {days}-day release cooldown set {today.isoformat()} (ADR-100).\n"
        f'exclude-newer = "{cutoff}"\n'
    )


def render_exemptions(exempt: dict[str, str]) -> str:
    lines = "".join(f'{name} = "{stamp}"\n' for name, stamp in sorted(exempt.items()))
    return "[tool.uv.exclude-newer-package]\n" + lines


def current_exemptions(text: str) -> dict[str, str]:
    begin = text.find("# >>> lockctl:exemptions\n")
    end = text.find("# <<< lockctl:exemptions\n")
    block = text[begin:end] if 0 <= begin < end else ""
    return dict(re.findall(r'^([a-z0-9-]+) = "([^"]+)"$', block, re.M))


def unexpired(exempt: dict[str, str], cutoff: str) -> dict[str, str]:
    """Exemptions still later than the cutoff: a fast-path exemption from last
    week survives the monthly run (it covers packages outside uv.lock too)."""
    return {name: stamp for name, stamp in exempt.items() if stamp > cutoff}


def cmd_cooldown(args: argparse.Namespace) -> int:
    today = dt.date.fromisoformat(args.today) if args.today else dt.date.today()
    cutoff = cutoff_for(today, args.days)
    text = PYPROJECT.read_text()
    exempt = merge_exemptions(
        exemptions(parse_uv_lock(UV_LOCK.read_text()), cutoff),
        unexpired(current_exemptions(text), cutoff),
    )
    text = replace_block(text, "cooldown", render_cooldown(cutoff, args.days, today))
    PYPROJECT.write_text(replace_block(text, "exemptions", render_exemptions(exempt)))
    print(f"cutoff {cutoff}; {len(exempt)} exemption(s): {', '.join(sorted(exempt)) or 'none'}")
    return 0


def cmd_allow_new(args: argparse.Namespace) -> int:
    now = _now()
    text = PYPROJECT.read_text()
    if not re.search(r'^exclude-newer = "', text, re.M):
        # No cooldown yet: `uv lock --upgrade-package` alone is the fast path.
        # An exemption without a global cutoff would make uv drop the lock and
        # re-resolve EVERY package to its newest release (tested 2026-10-26).
        print("no cooldown configured: nothing to exempt")
        return 0
    exempt = current_exemptions(text)
    exempt.update({canonical(name): now for name in args.packages})
    PYPROJECT.write_text(replace_block(text, "exemptions", render_exemptions(exempt)))
    print(f"exempted until {now}: {', '.join(args.packages)}")
    return 0


# ── derive umrs/src/uv.lock ─────────────────────────────────────────────────


def umrs_constraints() -> list[str]:
    body = _run(
        [
            "uv",
            "export",
            "--frozen",
            "--no-hashes",
            "--no-header",
            "--no-annotate",
            "--no-dev",
            "--no-emit-workspace",
            "--package",
            "umrs",
            "--all-extras",
        ]
    )
    return requirement_lines(body)


def standalone_pyproject(text: str, constraints: list[str]) -> str:
    """umrs's pyproject plus the workspace versions as constraints and a path
    source for r4-contracts (scratch copy only; never committed)."""
    listed = "".join(f'    "{line}",\n' for line in constraints)
    table = "[tool.uv]\nconstraint-dependencies = [\n" + listed + "]\n"
    if "[tool.uv]\n" in text:
        text = text.replace("[tool.uv]\n", table, 1)
    else:
        text += "\n" + table
    return (
        text
        + '\n[tool.uv.sources]\nr4-contracts = { path = "../../r4-contracts", editable = true }\n'
    )


def cmd_derive_umrs(_args: argparse.Namespace) -> int:
    constraints = umrs_constraints()
    with tempfile.TemporaryDirectory(prefix="lockctl-") as tmp:
        project = Path(tmp) / "umrs" / "src"
        project.mkdir(parents=True)
        source = (ROOT / "umrs" / "src" / "pyproject.toml").read_text()
        (project / "pyproject.toml").write_text(standalone_pyproject(source, constraints))
        contracts = Path(tmp) / "r4-contracts"
        shutil.copytree(
            ROOT / "r4-contracts", contracts, ignore=shutil.ignore_patterns(".*", "__pycache__")
        )
        _run(["uv", "lock"], cwd=project)
        shutil.copyfile(project / "uv.lock", UMRS_LOCK)
    print(f"wrote umrs/src/uv.lock ({len(constraints)} workspace pins)")
    return 0


# ── check (offline) ─────────────────────────────────────────────────────────


def _workspace_files(lock: WorkspaceLock) -> list[str]:
    return [rel for rel in (lock.out, lock.cpu_out, lock.torch_cpu_out) if rel]


def _version_problem(rel: str, pin: tuple[str, str], entry: LockedPackage | None) -> str:
    name, version = pin
    if entry is not None and version in entry.versions:
        return ""
    have = sorted(entry.versions) if entry else "absent"
    return f"{rel}: {name}=={version} but uv.lock has {have}"


def workspace_lock_problems(rel: str, text: str, locked: dict[str, LockedPackage]) -> list[str]:
    problems = [f"{rel}: not pinned: {line}" for line in unpinned_lines(text)]
    problems += [_version_problem(rel, pin, locked.get(pin[0])) for pin in pins(text).items()]
    return [problem for problem in problems if problem]


def compiled_lock_problems(rel: str, text: str, locked: dict[str, LockedPackage]) -> list[str]:
    """A compiled lock pins every line and agrees with uv.lock on every
    package uv.lock also holds (the rest is outside the workspace)."""
    problems = [f"{rel}: not pinned: {line}" for line in unpinned_lines(text)]
    shared = [pin for pin in pins(text).items() if pin[0] in locked]
    problems += [_version_problem(rel, pin, locked[pin[0]]) for pin in shared]
    problems += [] if text else [f"{rel}: missing (run lockctl.py export)"]
    return [problem for problem in problems if problem]


def drift(rel: str, want: str, have: str) -> list[str]:
    """[] when a lock file is exactly the export, else what it lacks and adds."""
    if want == have:
        return []
    missing = sorted(set(requirement_lines(want)) - set(requirement_lines(have)))
    extra = sorted(set(requirement_lines(have)) - set(requirement_lines(want)))
    return [
        f"{rel}: not what `uv export` emits (run lockctl.py export);"
        f" lacks {missing or 'nothing'}, adds {extra or 'nothing'}"
    ]


def _read(path: Path) -> str:
    return path.read_text() if path.is_file() else ""


def export_problems(root: Path = ROOT) -> list[str]:
    """Each workspace image lock against a fresh `uv export --frozen` (offline)."""
    problems: list[str] = []
    for lock in WORKSPACE_LOCKS.values():
        for rel, want in export_workspace(lock, root).items():
            problems += drift(rel, want, _read(root / rel))
    return problems


def present_compiled_locks(root: Path = ROOT) -> list[CompiledLock]:
    """The compiled locks of this tree. A lock whose input and output are
    both absent is not part of it (the public export leaves out the sites'
    Ansible files); one half without the other still fails the check."""
    return [
        lock
        for lock in COMPILED_LOCKS.values()
        if (root / lock.src).exists() or (root / lock.out).exists()
    ]


def check_problems(root: Path = ROOT) -> list[str]:
    """Every image lock exists, pins every line, and matches uv.lock: the
    workspace locks exactly (both directions), the compiled ones on every
    package uv.lock holds."""
    locked = parse_uv_lock((root / "uv.lock").read_text())
    problems = export_problems(root)
    for lock in WORKSPACE_LOCKS.values():
        for rel in _workspace_files(lock):
            problems += workspace_lock_problems(rel, _read(root / rel), locked)
    for lock in present_compiled_locks(root):
        problems += compiled_lock_problems(lock.out, _read(root / lock.out), locked)
    return problems


def umrs_lock_problems(root: Path = ROOT) -> list[str]:
    """umrs/src/uv.lock (derived) must hold the workspace lock's versions."""
    workspace = parse_uv_lock((root / "uv.lock").read_text())
    derived = parse_uv_lock((root / "umrs" / "src" / "uv.lock").read_text())
    problems = []
    for name, entry in sorted(derived.items()):
        have = workspace.get(name)
        if name in LOCAL_PACKAGES or (have and entry.versions <= have.versions):
            continue
        problems.append(
            f"umrs/src/uv.lock: {name} {sorted(entry.versions)} not in uv.lock (run lockctl.py derive-umrs)"
        )
    return problems


# ── Dockerfile rule ─────────────────────────────────────────────────────────

VALUE_FLAGS = {"-r", "--requirement", "-c", "--constraint", "-e", "--editable", "-i", "--index-url"}


def _run_commands(text: str) -> list[str]:
    """Shell commands of every RUN instruction, continuations joined."""
    joined = re.sub(r"\\\n", " ", text)
    runs = [line[4:] for line in joined.splitlines() if line.startswith("RUN ")]
    separators = r"&&|\|\||;|\bthen\b|\belse\b|\bfi\b"
    return [part.strip() for run in runs for part in re.split(separators, run)]


def pip_installs(text: str) -> list[list[str]]:
    """Argument lists of every `pip install` / `uv pip install` in a Dockerfile."""
    found = []
    for command in _run_commands(text):
        match = re.search(r"\bpip install\b(.*)", command)
        if match:
            found.append(shlex.split(match.group(1)))
    return found


def _value_problem(flag: str, value: str) -> str:
    if flag in ("-r", "--requirement") and not value.endswith(".lock.txt"):
        return f"-r {value} is not a lock"
    if flag in ("-e", "--editable") and not value.startswith(("/", ".")):
        return f"-e {value} is not a local path"
    return ""


def install_problems(args: list[str]) -> list[str]:
    """Why one `pip install` is not locked ([] when it is)."""
    problems = [] if "--no-deps" in args else ["no --no-deps"]
    items = iter(args)
    for arg in items:
        if arg in VALUE_FLAGS:
            problems.append(_value_problem(arg, next(items, "")))
        elif not arg.startswith(("-", "/", ".")):
            problems.append(f"unlocked package {arg}")
    return [problem for problem in problems if problem]


def dockerfile_problems(text: str) -> list[str]:
    """Every unlocked `pip install` of a Dockerfile, as readable lines."""
    return [
        f"pip install {' '.join(args)}: {why}"
        for args in pip_installs(text)
        for why in install_problems(args)
    ]


def cmd_check(_args: argparse.Namespace) -> int:
    problems = check_problems() + umrs_lock_problems()
    for problem in problems:
        print(problem, file=sys.stderr)
    print("lockctl check: " + ("FAILED" if problems else "ok"))
    return 1 if problems else 0


def version_changes(old: str, new: str) -> list[str]:
    """`name: old -> new` for every package whose locked versions moved."""
    before, after = parse_uv_lock(old), parse_uv_lock(new)
    lines = []
    for name in sorted(set(before) | set(after)):
        was = sorted(before[name].versions) if name in before else []
        now = sorted(after[name].versions) if name in after else []
        if was != now:
            lines.append(f"{name}: {', '.join(was) or '(new)'} -> {', '.join(now) or '(removed)'}")
    return lines


def cmd_changes(args: argparse.Namespace) -> int:
    old = Path(args.old_lock).read_text()
    for line in version_changes(old, UV_LOCK.read_text()):
        print(line)
    return 0


def parser() -> argparse.ArgumentParser:
    top = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    sub = top.add_subparsers(dest="cmd", required=True)
    cooldown = sub.add_parser("cooldown")
    cooldown.add_argument("--days", type=int, default=7)
    cooldown.add_argument("--today", default="")
    cooldown.set_defaults(func=cmd_cooldown)
    allow = sub.add_parser("allow-new")
    allow.add_argument("packages", nargs="+")
    allow.set_defaults(func=cmd_allow_new)
    export = sub.add_parser("export")
    export.add_argument("--upgrade", action="store_true")
    export.add_argument("--upgrade-package", action="append", default=[])
    export.set_defaults(func=cmd_export)
    sub.add_parser("derive-umrs").set_defaults(func=cmd_derive_umrs)
    sub.add_parser("check").set_defaults(func=cmd_check)
    changes = sub.add_parser("changes")
    changes.add_argument("old_lock")
    changes.set_defaults(func=cmd_changes)
    return top


def main(argv: list[str] | None = None) -> int:
    args = parser().parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
