#!/usr/bin/env python3
"""Regenerate the v3 slash reachability fixture from the Python registry.

Plan H-5 (2026-10-18). ``packages/r4-tui-v3/tests/slash-reachability.test.ts``
dispatches every Python registry command, alias and subcommand through the v3
dispatcher; it reads the registry and the ``list_slash_commands`` catalog from
the JSON fixture this script writes, because bun cannot import Python.

It also copies the v3 slash manifest
(``packages/r4-tui-v3/src/commands/catalog.manifest.json``, the one place
slash ownership is declared) into the r4 package
(``r4/src/r4/companion/ui/slash_catalog.manifest.json``): the wheel ships only
``src/r4``, and the bridge reads its aliases and surface rows from the copy.

    .venv/bin/python scripts/regen-slash-fixture.py          # rewrite
    .venv/bin/python scripts/regen-slash-fixture.py --check  # exit 1 if stale

``r4/tests/test_tui_audit_bridge.py`` runs ``--check`` so the fixture cannot
go stale. Run as a script, r4 is imported under a scratch HOME: the fixture
must never depend on the developer's ``~/.config/r4``.
"""

from __future__ import annotations

import argparse
import atexit
import json
import os
import shutil
import sys
import tempfile
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[1]
FIXTURE = REPO / "packages" / "r4-tui-v3" / "tests" / "fixtures" / "python-slash-registry.json"
MANIFEST = REPO / "packages" / "r4-tui-v3" / "src" / "commands" / "catalog.manifest.json"
SCRIPT = "scripts/regen-slash-fixture.py"
MANIFEST_COPY = REPO / "r4" / "src" / "r4" / "companion" / "ui" / "slash_catalog.manifest.json"


def _registry_rows() -> list[dict[str, Any]]:
    from r4.tui.commands import SUBCOMMANDS, get_slash_registry

    return [
        {
            "name": command.name,
            "aliases": list(command.aliases),
            "subcommands": [sub.name for sub in SUBCOMMANDS.get(command.name, [])],
        }
        for command in get_slash_registry().command_list()
    ]


def build_fixture() -> dict[str, Any]:
    """The registry rows plus the catalog the bridge exports to v3."""
    from r4.companion.ui.bridge_server import CompanionBridgeServer

    catalog = CompanionBridgeServer().list_slash_commands({})["commands"]
    return {
        "_comment": "Generated by scripts/regen-slash-fixture.py; do not edit by hand.",
        "registry": _registry_rows(),
        "catalog": catalog,
    }


def render(data: dict[str, Any]) -> str:
    return json.dumps(data, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8") if path.exists() else ""


def check(manifest: str) -> int:
    """0 when the manifest copy and the fixture are current, else 1."""
    # The catalog is built from the copy: a stale copy is reported first.
    for path, fresh in (
        (MANIFEST_COPY, lambda: manifest),
        (FIXTURE, lambda: render(build_fixture())),
    ):
        if _read(path) != fresh():
            print(f"stale: {path.relative_to(REPO)}; run {SCRIPT}", file=sys.stderr)
            return 1
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when an output is stale")
    args = parser.parse_args(argv)
    manifest = MANIFEST.read_text(encoding="utf-8")
    if args.check:
        return check(manifest)
    MANIFEST_COPY.write_text(manifest, encoding="utf-8")
    FIXTURE.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE.write_text(render(build_fixture()), encoding="utf-8")
    print(f"wrote {MANIFEST_COPY.relative_to(REPO)} and {FIXTURE.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    _home = tempfile.mkdtemp(prefix="r4-slash-fixture-home-")
    atexit.register(shutil.rmtree, _home, True)
    os.environ["HOME"] = _home
    os.environ["XDG_CONFIG_HOME"] = os.path.join(_home, ".config")
    sys.exit(main())
